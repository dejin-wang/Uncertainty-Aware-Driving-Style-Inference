import ast
import numpy as np
import pandas as pd
import torch
import torch.nn as nn
from torch.utils.data import Dataset, DataLoader, random_split



class TrajectoryDataset(Dataset):
    """Dataset that reads (state, action) pairs from the CSV file."""
    def __init__(self, csv_path: str, use_style: bool = False):
        """
        Args:
            csv_path: Path to the CSV file generated by the PPO rollout script.
            use_style: If True, concatenates style vector to the state as input.
        """
        self.df = pd.read_csv(csv_path)
        self.use_style = use_style

        self.states = []
        self.actions = []

        for _, row in self.df.iterrows():
            # Parse state
            obs = np.array(ast.literal_eval(row["Obs(flat)"]), dtype=np.float32)

            # Optionally append style
            if self.use_style:
                style = np.array(ast.literal_eval(row["Style"]), dtype=np.float32)
                obs = np.concatenate([obs, style], axis=0)

            # Parse action
            action = np.array(ast.literal_eval(row["Action"]), dtype=np.float32)

            self.states.append(obs)
            self.actions.append(action)

        self.states = np.stack(self.states, axis=0)
        self.actions = np.stack(self.actions, axis=0)

    def __len__(self) -> int:
        return self.states.shape[0]

    def __getitem__(self, idx: int):
        state = torch.from_numpy(self.states[idx])
        action = torch.from_numpy(self.actions[idx])
        return state, action


class PolicyNet(nn.Module):
    """Simple MLP that maps state to continuous action."""
    def __init__(self, input_dim: int, output_dim: int, hidden_sizes=(256, 256, 256)):
        super().__init__()
        layers = []
        prev_dim = input_dim
        for h in hidden_sizes:
            layers.append(nn.Linear(prev_dim, h))
            layers.append(nn.ReLU())
            prev_dim = h
        layers.append(nn.Linear(prev_dim, output_dim))
        self.net = nn.Sequential(*layers)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.net(x)



def main():
    csv_path = "PPO_obs_and_rewards_regression.csv"
    use_style_as_input = False  # set True if you want [state, style] -> action

    # 1. Build dataset
    dataset = TrajectoryDataset(csv_path, use_style=use_style_as_input)

    # Infer dimensions
    sample_state, sample_action = dataset[0]
    input_dim = sample_state.shape[0]
    output_dim = sample_action.shape[0]
    print(f"Input dim: {input_dim}, Action dim: {output_dim}")

    # 2. Train/val split
    val_ratio = 0.1
    val_size = int(len(dataset) * val_ratio)
    train_size = len(dataset) - val_size
    train_set, val_set = random_split(dataset, [train_size, val_size])

    train_loader = DataLoader(train_set, batch_size=256, shuffle=True)
    val_loader = DataLoader(val_set, batch_size=256, shuffle=False)

    # 3. Create model, optimizer, loss
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = PolicyNet(input_dim=input_dim, output_dim=output_dim).to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=1e-3)
    criterion = nn.MSELoss()

    num_epochs = 50

    for epoch in range(1, num_epochs + 1):
        # ----- Training -----
        model.train()
        train_loss = 0.0
        for states, actions in train_loader:
            states = states.to(device)
            actions = actions.to(device)

            pred_actions = model(states)
            loss = criterion(pred_actions, actions)

            optimizer.zero_grad()
            loss.backward()
            optimizer.step()

            train_loss += loss.item() * states.size(0)

        train_loss /= len(train_set)

        # ----- Validation -----
        model.eval()
        val_loss = 0.0
        with torch.no_grad():
            for states, actions in val_loader:
                states = states.to(device)
                actions = actions.to(device)

                pred_actions = model(states)
                loss = criterion(pred_actions, actions)
                val_loss += loss.item() * states.size(0)
        val_loss /= len(val_set)

        print(f"Epoch [{epoch}/{num_epochs}] "
              f"Train MSE: {train_loss:.6f}  Val MSE: {val_loss:.6f}")

    # 4. Save model
    torch.save(model.state_dict(), "bc_policy_from_csv.pth")
    print("Model saved to bc_policy_from_csv.pth")

    # 5. Example of using the trained model for inference
    model.eval()
    with torch.no_grad():
        example_state, _ = dataset[0]
        example_state = example_state.to(device)
        pred_action = model(example_state.unsqueeze(0))[0].cpu().numpy()
        print("Example predicted action:", pred_action)


if __name__ == "__main__":
    main()
